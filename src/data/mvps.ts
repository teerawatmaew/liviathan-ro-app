/** กรอง MVP ตาม difficulty */
export function getMvpsByDifficulty(difficulty: MvpDifficulty) {
  return mvps.filter((m) => m.difficulty === difficulty)
}

/** กรอง MVP ตาม spawnType */
export function getNormalMvps() {
  return mvps.filter((m) => m.spawnType === 'normal')
}

/** หา MVP จาก id */
export function getMvpById(id: string) {
  return mvps.find((m) => m.id === id) ?? null
}
